on public.goleadores_oficiales
for select
to anon, authenticated
using (true);

revoke all on table public.goleadores_oficiales
  from public, anon, authenticated;

grant select on table public.goleadores_oficiales
  to anon, authenticated;

grant select, insert, update, delete on table public.goleadores_oficiales
  to service_role;

