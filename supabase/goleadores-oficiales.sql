  id bigint generated by default as identity primary key,
  torneo_id bigint not null references public.torneos(id),
  posicion integer not null check (posicion > 0),
  equipo_id bigint null references public.clubes(id),
  equipo_nombre text not null check (btrim(equipo_nombre) <> ''),
  jugador_nombre text not null check (btrim(jugador_nombre) <> ''),
  goles integer not null check (goles >= 0),
  fuente text not null check (btrim(fuente) <> ''),
  fecha_fuente date null,
  observaciones text null,
  creado_en timestamptz not null default now()
);

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where
      conname = 'goleadores_oficiales_torneo_posicion_key'
      and conrelid = 'public.goleadores_oficiales'::regclass
  ) then
    alter table public.goleadores_oficiales
      add constraint goleadores_oficiales_torneo_posicion_key
      unique (torneo_id, posicion);
  end if;
end;
$$;

