  to anon, authenticated;

grant select, insert, update, delete on table public.goleadores_oficiales
  to service_role;

do $$
declare
  v_sequence text;
begin
  select pg_get_serial_sequence(
    'public.goleadores_oficiales',
    'id'
  )
  into v_sequence;

  if v_sequence is not null then
    execute format(
      'grant usage, select on sequence %s to service_role',
      v_sequence
    );
  end if;
end;
$$;

