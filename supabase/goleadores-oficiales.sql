  observaciones text null,
  creado_en timestamptz not null default now()
);

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where
      conname = 'goleadores_oficiales_torneo_posicion_key'
      and conrelid = 'public.goleadores_oficiales'::regclass
  ) then
    alter table public.goleadores_oficiales
      add constraint goleadores_oficiales_torneo_posicion_key
      unique (torneo_id, posicion);
  end if;
end;
$$;

